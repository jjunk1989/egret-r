// Bundle individual .d.ts from tsc into single index.d.ts
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, '..');

function walkDts(dir) {
  const results = [];
  if (!fs.existsSync(dir)) return results;
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  for (const e of entries) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) results.push(...walkDts(p));
    else if (e.isFile() && p.endsWith('.d.ts')) results.push(p);
  }
  return results;
}

function convertToNamespace(content) {
  content = content.replace(/^import\s+type\s+.*$/gm, '');
  content = content.replace(/^import\s+\{.*?\}\s+from\s+["'][^"']+["'];?\s*$/gm, '');
  content = content.replace(/^import\s+\*\s+as\s+\w+\s+from\s+["'][^"']+["'];?\s*$/gm, '');
  content = content.replace(/^import\s+["'][^"']+["'];?\s*$/gm, '');
  content = content.replace(/^\/\/# sourceMappingURL.*$/gm, '');
  content = content.replace(/^export\s+(default\s+)?/gm, '');
  return content.trim();
}

function bundle(pkgName, distDir, srcFilter) {
  const dtsFiles = walkDts(distDir).filter(f => {
    const basename = path.basename(f);
    return basename !== 'index.d.ts' && basename !== '_entry.d.ts';
  }).sort();

  if (dtsFiles.length === 0) { console.log('  No files for ' + pkgName); return; }

  const nsBlocks = {};
  for (const f of dtsFiles) {
    const rel = path.relative(distDir, f);
    const ns = srcFilter ? srcFilter(rel) : 'egret';
    const content = fs.readFileSync(f, 'utf8');
    const converted = convertToNamespace(content);
    if (converted) {
      if (!nsBlocks[ns]) nsBlocks[ns] = [];
      nsBlocks[ns].push('// ' + rel + '\n' + converted);
    }
  }

  let dts = '// Type definitions for @egret-r\n';
  dts += '// Auto-generated by tsc --emitDeclarationOnly. Do not edit.\n\n';
  if (pkgName !== 'core') {
    dts += "import { egret } from '@egret-r/core';\n\n";
  }

  const allNs = Object.keys(nsBlocks);
  for (const ns of allNs) {
    dts += 'declare namespace ' + ns + ' {\n';
    dts += nsBlocks[ns].join('\n\n');
    dts += '\n}\n\n';
  }

  dts += 'export as namespace egret;\n';
  if (allNs.length > 0) {
    dts += '\nexport { ' + allNs.join(', ') + ' };\n';
  }

  const outPath = path.join(distDir, 'index.d.ts');
  fs.writeFileSync(outPath, dts, 'utf8');
  console.log('  ' + pkgName + ': ' + fs.statSync(outPath).size.toLocaleString() + ' bytes, ' + dtsFiles.length + ' files');
}

console.log('Bundling core .d.ts...');
bundle('core', path.join(ROOT, 'packages/core/dist'), null);
console.log('Done.');
